/**
 * The animator, split into small bounded calls so no answer can run away:
 *   1 call  → KIT: drawings shared by several scenes (≤ ~150 lines)
 *   N calls → one function per scene (≤ ~90 lines each), 3 at a time
 * Every raw answer is saved under <film>/claude/ for debugging. Fix rounds redo only the scenes that broke.
 */

const ASSETS = path.join(process.cwd(), "assets/explainer");
const read = (f: string) => fs.readFileSync(path.join(ASSETS, f), "utf8");

const RULES = `REGRAS (Vitrine):
- Canvas 1080x1920 (9:16), estilo flat. O shell já pinta o fundo (H.B.bg), o nome da série no topo e um flash na troca de cena — NÃO repita isso.
- LAYOUT: títulos/números só em H.Z.top; a ilustração em H.Z.mid, GRANDE (use quase toda a largura e altura da zona); NADA em H.Z.caption (y ≥ 1330): ali entram as legendas da narração. Centralize em H.Z.cx (o TikTok cobre a borda direita).
- PRIMEIRO QUADRO (cena 0): no instante t = 0 a tela já precisa estar CHEIA e legível — título do gancho grande e visível SEM animação de entrada (desenhe com H.txt, não H.stamp), ilustração grande, colorida e contrastante ocupando a zona do meio, e algo já se mexendo. Nada de tela escura ou vazia no começo: é o quadro que decide se a pessoa fica.
- TEMPO: t é o tempo absoluto do vídeo; a cena vai de s.t0 a s.t1. Todo acontecimento ligado à fala usa H.cue(i, 'palavra') com uma palavra EXATA da narração da cena i.
- Uma ideia visual por cena, MOSTRADA acontecendo (antes → depois, crescer, medir, comparar, setas), não só texto. Formas simples e limpas.
- Função pura de t: nada de Math.random/Date.now (use H.U.hash), sem estado entre frames, sem imagens externas.
- Texto ≥ 34px, curto (use o título da cena), cores da marca (H.B.gold, H.B.ink) e do tema (H.PAL).
- MOVIMENTO CONSTANTE: nada parado por mais de ~1 s. Elementos ENTRAM animados (deslizar, crescer, linha se desenhando, contador subindo), cada palavra-chave da narração dispara um acontecimento (H.cue), e enquanto espera algo respira (balanço, pulsar, brilho). Pelo menos 2–3 acontecimentos por cena. O shell já faz um leve zoom de câmera em cada cena.
- O @ do perfil (H.handle) já aparece no topo pelo shell; na cena final, destaque H.handle junto do CTA. Nunca escreva outro @.
- Código ENXUTO: sem comentários longos, sem listas enormes de coordenadas, sem repetir o que está no kit.`;

const SYSTEM = () => [{
  type: "text", cache_control: { type: "ephemeral" },
  text: `Você é animador de motion graphics. Escreve código JavaScript de canvas 2D para o motor "animation-studio", no formato de KIT + funções de cena mostrado no exemplo.

API DO MOTOR (G, Data, U):
${read("engine-api.md")}

${RULES}
${styleBrief() ? "\n" + styleBrief() + "\n" : ""}
EXEMPLO DO FORMATO (tema "60-30-10"; siga o formato e a qualidade, não o conteúdo):
\`\`\`js
${read("example-scenes.js")}
\`\`\`

Responda SEMPRE só com os blocos pedidos, sem texto antes ou depois.`,
}];

function overview(plan: TExplainerPlan, narr: Narr) {
  return plan.scenes.map((s, i) => {
    const sc = narr.scenes[i];
    const ws = narr.words.filter((w) => w.scene === i).map((w) => `${w.w}@${w.t0.toFixed(2)}`).join(" ");
    return `CENA ${i} [${sc.t0.toFixed(2)}s → ${sc.t1.toFixed(2)}s] título: "${s.onScreen}"
  narração: "${s.narration}"
  palavras: ${ws}
  visual: ${s.visual}`;
  }).join("\n");
}

const block = (t: string, lang: string) => t.match(new RegExp("```" + lang + "\\n([\\s\\S]*?)```"))?.[1];

function checkSyntax(code: string, label: string) {
  try { new vm.Script("(" + code + ")"); return null; } catch (e) { return `${label}: erro de sintaxe — ${(e as Error).message}`; }
}

/** The fixed shell around the kit and the scenes. */
export function assemble(kit: string, scenes: string[]) {
  return `// GENERATED by Vitrine (shell + kit + one function per scene)
(function () {
  const U = globalThis.U, G = globalThis.G, S = globalThis.SCORE, Studio = globalThis.Studio, Data = globalThis.Data;
  const { clamp, lerp, ease } = U;
  const Z = S.ZONES, B = S.BRAND, F = 'Poppins';
  const H = {
    U, G, Data, W: G.W, H: G.H, clamp, lerp, ease, Z, B, PAL: S.PALETTE, C: S.OBJECTS || {}, F, cue: S.cue, handle: S.HANDLE || '',
    R: (ctx, x, y, w, h, r, fill) => G.rrect(ctx, x, y, w, h, r, { fill, lw: 0 }),
    E: (ctx, cx, cy, rx, ry, fill) => G.ellipse(ctx, cx, cy, rx, ry, { fill, lw: 0 }),
    txt: (ctx, s, x, y, o) => G.text(ctx, s, x, y, { fam: F, weight: 700, color: B.ink, ...o }),
    prog: (t, a, b) => clamp((t - a) / Math.max(1e-6, b - a)),
    stamp(ctx, s, x, y, t, t0, o = {}) {
      const a = clamp((t - t0) / 0.22); if (a <= 0) return;
      const k = lerp(1.6, 1, ease.outBack(a, 2));
      ctx.save(); ctx.translate(x, y); ctx.scale(k, k); H.txt(ctx, s, 0, 0, { alpha: clamp(a * 2), ...o }); ctx.restore();
    },
    arrow(ctx, x1, y1, x2, y2, { color = B.gold, lw = 8, head = 26, p = 1 } = {}) {
      if (p <= 0) return; const x = lerp(x1, x2, p), y = lerp(y1, y2, p), a = Math.atan2(y - y1, x - x1);
      ctx.save(); ctx.strokeStyle = ctx.fillStyle = color; ctx.lineWidth = lw; ctx.lineCap = 'round';
      ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x, y); ctx.stroke();
      ctx.beginPath(); ctx.moveTo(x, y); ctx.lineTo(x - head * Math.cos(a - 0.45), y - head * Math.sin(a - 0.45)); ctx.lineTo(x - head * Math.cos(a + 0.45), y - head * Math.sin(a + 0.45)); ctx.fill();
      ctx.restore();
    },
  };
  let K = {};
  try { K = (${kit})(H) || {}; } catch (e) { throw new Error('kit: ' + (e && e.message)); }
  const SC = [
${scenes.map((c, i) => `    /* cena ${i} */ (${c}),`).join("\n")}
  ];
  const sceneAt = (t) => Math.max(0, S.SCENES.findIndex((s) => t >= s.t0 && t < s.t1));
  Studio.film({
    async init() { await Studio.loadFont(F, 'assets/Poppins-Bold.ttf', 700); await Studio.loadFont(F, 'assets/Poppins-Medium.ttf', 500); },
    draw(ctx, t) {
      ctx.fillStyle = B.bg; ctx.fillRect(0, 0, G.W, G.H);
      const i = sceneAt(t), s = S.SCENES[i];
      // gentle camera: slow push-in over the scene + a short settle when it starts (keeps every shot alive)
      const p = clamp((t - s.t0) / Math.max(0.5, s.t1 - s.t0)), enter = i === 0 ? 0 : 1 - ease.outCubic(clamp((t - s.t0) / 0.35));
      const k = 1 + 0.035 * ease.inOutQuad(p), cy = Z.mid.y + Z.mid.h / 2;
      try { ctx.save(); ctx.translate(Z.cx, cy + 36 * enter); ctx.scale(k, k); ctx.translate(-Z.cx, -cy); SC[i](ctx, t, s, H, K); ctx.restore(); }
      catch (e) { throw new Error('cena ' + i + ': ' + (e && e.message)); }
      const tag = [S.series ? S.series.toUpperCase() : '', H.handle].filter(Boolean).join('  ·  ');
      if (tag) H.txt(ctx, tag, Z.top.x, Z.top.y + 30, { size: 30, color: B.gold, weight: 500 });
      const fl = i > 0 ? 0.45 * Math.exp(-(t - s.t0) * 12) : 0;
      if (fl > 0.01) { ctx.fillStyle = 'rgba(255,248,232,' + fl + ')'; ctx.fillRect(0, 0, G.W, G.H); }
    },
    post: { paper: 0.12, vignette: 0.3, grain: 0.04 },
  });
})();
`;
}

/** Which scenes a QA/exception line is about (by "cena N" or by its time range). */
function scenesOf(issue: string, narr: Narr): number[] {
  const m = issue.match(/cena (\d+)/);
  if (m) return [Number(m[1])];
  if (/kit:/.test(issue)) return [-1];
  const tm = issue.match(/(\d+(?:\.\d+)?)(?:[–-](\d+(?:\.\d+)?))?s/);
  if (tm) {
    const a = +tm[1], b = tm[2] ? +tm[2] : a;
    return narr.scenes.map((s, i) => (s.t1 > a && s.t0 <= b ? i : -2)).filter((i) => i >= 0);
  }
  return [];
}

export async function authorFilm(ctx: Ctx, dir: string, plan: TExplainerPlan, narr: Narr): Promise<string[]> {
  if (process.env.EXPLAINER_FILM) { // hand-written full film (tests / manual tweaks)
    fs.copyFileSync(process.env.EXPLAINER_FILM, path.join(dir, "film.js"));
    writeSfx(dir, process.env.EXPLAINER_SFX ? JSON.parse(fs.readFileSync(process.env.EXPLAINER_SFX, "utf8")) : [], narr);
    return (await review(dir, narr, ctx.log)).issues;
  }
  if (config.llmProvider === "mock") {
    fs.copyFileSync(path.join(ASSETS, "mock-film.js"), path.join(dir, "film.js"));
    writeSfx(dir, narr.scenes.map((_, i) => ({ scene: i, at: 0, kind: "whoosh" })), narr);
    return (await review(dir, narr, ctx.log)).issues;
  }

  const rawDir = path.join(dir, "claude");
  fs.mkdirSync(rawDir, { recursive: true });
  const system: any = SYSTEM();
  const head = `FILME: "${plan.title}" · série "${plan.series}" · ${narr.duration.toFixed(1)}s · paleta do tema: ${plan.palette.join(", ") || "livre"}\n\nTODAS AS CENAS (para manter continuidade):\n${overview(plan, narr)}`;

  async function ask(label: string, user: string, maxTokens: number) {
    const t0 = Date.now();
    const res = await askClaude({ model: config.anthropicModel, max_tokens: maxTokens, system, messages: [{ role: "user", content: user }] });
    const c = claudeCost(res.usage);
    const cut = res.stop_reason === "max_tokens";
    ctx.cost({ stage: "animação", provider: config.anthropicModel, usd: c.usd, note: `${label} · ${c.note}${cut ? " · CORTADA" : ""}` });
    const text = textOf(res);
    fs.writeFileSync(path.join(rawDir, `${label.replace(/\W+/g, "-")}-${Date.now()}.txt`),
      `stop_reason: ${res.stop_reason}\nblocks: ${res.content.map((b) => b.type).join(",")}\nusage: ${JSON.stringify(res.usage)}\n\n${text}`);
    ctx.log(`${label}: ${Math.round((Date.now() - t0) / 1000)}s, ${res.usage.output_tokens} tokens${cut ? " (CORTADA)" : ""}`);
    return { text, cut };
  }

  // ---------- kit ----------
  let kit = "function kit(H) { return {}; }";
  async function writeKit(extra = "") {
    for (let a = 0; a < 2; a++) {
      const r = await ask("kit", `${head}\n\nEscreva o KIT: as funções de desenho que MAIS DE UMA cena vai usar (o ambiente/objeto principal, como no exemplo). Máximo ~150 linhas. Se nada se repete, devolva um kit vazio.${extra}\n\nResponda com um bloco \`\`\`js contendo apenas: function kit(H) { ...; return { ... }; }`, 8000);
      const code = !r.cut && block(r.text, "js");
      if (code && !checkSyntax(code, "kit")) { kit = code.trim(); return; }
      extra = "\n\nIMPORTANTE: a tentativa anterior veio cortada ou com erro de sintaxe. Seja mais curto.";
    }
    ctx.log("kit: seguindo com kit vazio");
  }

  // ---------- scenes (3 in parallel) ----------
  const scenes: string[] = plan.scenes.map(() => "function scene(ctx, t, s, H, K) {}");
  const sfx: Record<number, any[]> = {};
  async function writeScene(i: number, fix = "") {
    for (let a = 0; a < 2; a++) {
      const r = await ask(`cena ${i}`, `${head}\n\nKIT JÁ ESCRITO (use K.*):\n\`\`\`js\n${kit}\n\`\`\`\n\nAgora escreva SÓ a CENA ${i}${i === 0 ? " (gancho: precisa prender nos 2 primeiros segundos)" : i === plan.scenes.length - 1 ? " (final: recap + CTA)" : ""}. Máximo ~90 linhas.${fix}\n\nResponda com:\n1) um bloco \`\`\`json de efeitos sonoros desta cena: [{"word":"palavra","kind":"chime"},{"at":0,"kind":"whoosh"}] (kind: pop | whoosh | thud | chime; 1–3 itens);\n2) um bloco \`\`\`js contendo apenas: function scene(ctx, t, s, H, K) { ... }`, 6000);
      const code = !r.cut && block(r.text, "js");
      const err = code ? checkSyntax(code, `cena ${i}`) : "sem bloco js";
      if (code && !err) {
        scenes[i] = code.trim();
        try { sfx[i] = JSON.parse(block(r.text, "json") ?? "[]"); } catch { sfx[i] = []; }
        return;
      }
      fix = `\n\nIMPORTANTE: a tentativa anterior ${r.cut ? "veio cortada por tamanho — seja bem mais curto" : `falhou (${err})`}.`;
    }
    ctx.log(`cena ${i}: não saiu código válido, ficará vazia`);
  }
  async function pool(ids: number[], fn: (i: number) => Promise<void>, n = 3) {
    const q = [...ids];
    await Promise.all(Array.from({ length: Math.min(n, q.length) }, async () => { while (q.length) await fn(q.shift()!); }));
  }
  // ---------- ONE call writes kit + every scene (cheap: the big context is sent once) ----------
  ctx.log(`Claude animando o vídeo inteiro (kit + ${plan.scenes.length} cenas) numa chamada…`);
  const full = await ask("filme", `${head}

Escreva o filme INTEIRO no formato do exemplo. Responda só com estes blocos, nesta ordem:
1) um bloco \`\`\`json de efeitos sonoros do filme todo: [{"scene":0,"word":"palavra","kind":"chime"},{"scene":3,"at":0,"kind":"whoosh"}] (kind: pop | whoosh | thud | chime; 5–15 itens);
2) um bloco \`\`\`js com o KIT: function kit(H) { ...; return { ... }; } (≤ 150 linhas; desenhos usados por mais de uma cena);
3) para CADA cena, em ordem, um bloco \`\`\`js começando com a linha "// CENA i" seguida de function scene(ctx, t, s, H, K) { ... } (≤ 90 linhas cada).
Cena 0 é o gancho (prender nos 2 primeiros segundos); a última é recap + CTA. Código enxuto.`, 20000);
  const blocks = [...full.text.matchAll(/```(?:js|javascript)\n([\s\S]*?)```/g)].map((m) => m[1].trim());
  const kitCode = blocks.find((b) => /function kit\s*\(/.test(b));
  if (kitCode && !checkSyntax(kitCode, "kit")) kit = kitCode;
  else { ctx.log("kit não veio completo — pedindo só o kit"); await writeKit(); }
  const sceneBlocks = blocks.filter((b) => /function scene\s*\(/.test(b));
  sceneBlocks.forEach((b, k) => {
    const i = Number(b.match(/\/\/\s*CENA\s*(\d+)/i)?.[1] ?? k);
    const code = b.replace(/^\s*\/\/.*\n/, "").trim();
    if (i >= 0 && i < scenes.length && !checkSyntax(code, `cena ${i}`)) scenes[i] = code;
  });
  try {
    const all = JSON.parse(block(full.text, "json") ?? "[]");
    for (const x of Array.isArray(all) ? all : []) (sfx[x.scene] ??= []).push(x);
  } catch { /* no sfx is fine */ }
  // only scenes that did not come back usable get their own (small) call
  const missing = scenes.map((c, i) => (/\{\s*\}$/.test(c) ? i : -1)).filter((i) => i >= 0);
  if (missing.length) { ctx.log(`cena(s) ${missing.join(", ")} faltando — pedindo separadamente`); await pool(missing, (i) => writeScene(i)); }

  // ---------- assemble + review, fix only broken scenes ----------
  let issues: string[] = [];
  let layoutFixed = false;
  for (let round = 0; round < 3; round++) {
    fs.writeFileSync(path.join(dir, "film.js"), assemble(kit, scenes));
    writeSfx(dir, Object.entries(sfx).flatMap(([i, list]) => (list || []).map((x: any) => ({ ...x, scene: Number(i) }))), narr);
    issues = (await review(dir, narr, ctx.log)).issues;
    if (!issues.length) { ctx.log("animação passou na checagem ✔"); return []; }
    ctx.log(`checagem: ${issues.length} problema(s): ${issues.join(" | ").slice(0, 300)}`);
    if (round === 2) break;
    const crash = issues.some((x) => /EXCEPTION|Error|cena \d+:|kit:/.test(x));
    if (!crash && layoutFixed) break; // layout warnings get one paid fix round, not more
    if (!crash) layoutFixed = true;
    const byScene = new Map<number, string[]>();
    for (const iss of issues) for (const i of scenesOf(iss, narr)) byScene.set(i, [...(byScene.get(i) ?? []), iss]);
    if (!byScene.size) break; // nothing attributable → stop paying, ship with warnings
    if (byScene.has(-1)) await writeKit(`\n\nCORRIJA: ${byScene.get(-1)!.join("; ")}\nKit atual:\n\`\`\`js\n${kit}\n\`\`\``);
    const redo = [...byScene.keys()].filter((i) => i >= 0);
    ctx.log(`corrigindo cena(s) ${redo.join(", ")}…`);
    await pool(redo, (i) => writeScene(i, `\n\nCORRIJA estes problemas da checagem automática: ${byScene.get(i)!.join("; ")}\nCódigo atual da cena:\n\`\`\`js\n${scenes[i]}\n\`\`\``));
  }
  return issues;
}

const norm = (x: string) => x.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9%]/g, "");
/** Resolve SFX cues (scene + word/offset) to absolute times; the raw list is kept so a new narration can re-time them. */
export function writeSfx(dir: string, list: any[], narr: Narr) {
  fs.writeFileSync(path.join(dir, "sfx-src.json"), JSON.stringify(list));
  const out = list.map((s) => {
    const sc = narr.scenes[s.scene];
    if (!sc) return null;
    let t = sc.t0 + (Number(s.at) || 0);
    if (s.word != null) {
      const w = narr.words.find((x) => x.scene === s.scene && norm(x.w).startsWith(norm(String(s.word))));
      t = w ? w.t0 : sc.t0 + (sc.t1 - sc.t0) * 0.3;
    }
    return { t: +t.toFixed(3), kind: s.kind };
  }).filter(Boolean);
  fs.writeFileSync(path.join(dir, "sfx.json"), JSON.stringify(out));
}
