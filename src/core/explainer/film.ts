// ---------- running the engine ----------
function chromeEnv() {
  const env: NodeJS.ProcessEnv = { ...process.env, FFMPEG: config.ffmpeg };
  const mac = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
  if (!env.CHROME_PATH && !fs.existsSync(mac)) {
    try { env.CHROME_PATH = chromium.executablePath(); } catch { /* render.js will search PATH */ }
  }
  return env;
}

export function engine(dir: string, args: string[], timeoutMs = 15 * 60_000, onLine?: (l: string) => void): Promise<{ code: number; out: string }> {
  return new Promise((resolve) => {
    const p = spawn(process.execPath, args, { cwd: dir, env: chromeEnv() });
    let out = "", buf = "";
    const feed = (d: Buffer) => {
      out += d;
      if (!onLine) return;
      buf += d;
      const parts = buf.split(/\r?\n|\r/); buf = parts.pop() ?? "";
      for (const l of parts) if (l.trim()) onLine(l.trim());
    };
    p.stdout.on("data", feed);
    p.stderr.on("data", feed);
    const timer = setTimeout(() => p.kill("SIGTERM"), timeoutMs);
    p.on("close", (code) => { clearTimeout(timer); resolve({ code: code ?? 1, out }); });
  });
}

/** Logs at most every `ms` — for progress lines that arrive many times per second. */
export function throttled(log: (m: string) => void, ms = 10_000) {
  let last = 0;
  return (m: string, force = false) => { const now = Date.now(); if (force || now - last >= ms) { last = now; log(m); } };
}

/** Average brightness (0–255) of the middle zone of a still; the empty brand background is ~40. */
function midBrightness(png: string): number | null {
  if (!fs.existsSync(png)) return null;
  const r = spawnSync(config.ffmpeg, ["-v", "error", "-i", png, "-vf", "crop=iw*0.85:ih*0.38:iw*0.05:ih*0.3,format=gray,signalstats,metadata=print:key=lavfi.signalstats.YAVG:file=-", "-f", "null", "-"], { encoding: "utf8" });
  const m = (r.stdout || "").match(/YAVG=([\d.]+)/);
  return m ? Number(m[1]) : null;
}

/** Cheap automatic review: render one still per scene (catches crashes) + the engine's visual QA (layout/contrast). */
export async function review(dir: string, narr: Narr, log: (m: string) => void = () => {}) {
  const issues: string[] = [];
  log(`checando a animação: 1 quadro de cada cena (${narr.scenes.length})…`);
  const times = narr.scenes.map((s) => ((s.t0 + s.t1) / 2).toFixed(2));
  // + one still right after each scene starts: the middle of the screen must never sit empty waiting for a word
  const early = narr.scenes.map((s, i) => (i > 0 && s.t1 - s.t0 > 1 ? (s.t0 + 0.35).toFixed(2) : null));
  const st = await engine(dir, ["engine/render.js", "stills", ...times, ...early.filter(Boolean) as string[], "--draft"], 5 * 60_000);
  for (const l of st.out.split("\n")) if (/EXCEPTION|Error|warning: frames must/.test(l)) issues.push(l.trim().slice(0, 400));
  if (st.code !== 0 && !issues.length) issues.push(st.out.slice(-600));
  const empty: string[] = [];
  if (!issues.length) early.forEach((t, i) => {
    if (!t) return;
    const png = path.join(dir, "out/stills", `t_${String(Number(t).toFixed(2)).padStart(6, "0")}.png`);
    const y = midBrightness(png);
    if (y !== null && y < 55) empty.push(`cena ${i}: a zona do meio fica VAZIA no começo da cena (${t}s). Algo precisa já estar na tela ou entrando em s.t0 (a ilustração ou o componente principal); as palavras só disparam os detalhes.`);
  });
  if (!issues.length) {
    log("checando layout (texto fora da tela, sobreposição, contraste)…");
    const qa = await engine(dir, ["engine/render.js", "qa", ...times], 5 * 60_000);
    for (const l of qa.out.split("\n")) if (/^⚠/.test(l.trim()) && !/mid-transition/.test(l)) issues.push(l.trim());
  }
  issues.push(...empty);
  return { issues, stills: times.map((t) => path.join(dir, "out/stills", `t_${String(Number(t).toFixed(2)).padStart(6, "0")}.png`)) };
}

// ---------- final render ----------
export async function renderFilm(ctx: Ctx, dir: string) {
  installMotion(dir); // latest motion library
  if (loadSettings().captions) installCaptions(dir); else removeCaptions(dir); // Configurações → legenda on/off
  fs.copyFileSync(path.join(ASSETS, "song.js"), path.join(dir, "song.js")); // latest mix (e.g. no vinyl hiss) also for old projects
  ctx.log("gerando trilha e mixando a narração…");
  const song = await engine(dir, ["song.js"], 5 * 60_000);
  if (song.code !== 0) throw new Error("song.js falhou: " + song.out.slice(-500));
  ctx.log("renderizando quadros (alguns minutos)…");
  const prog = throttled(ctx.log, 10_000);
  const v = await engine(dir, ["engine/render.js", "video"], 30 * 60_000, (l) => {
    const m = l.match(/(\d+)\/(\d+) frames.*?([\d.]+) fps.*?eta (\d+)s/);
    if (m) prog(`render: ${m[1]}/${m[2]} quadros (${Math.round((+m[1] / +m[2]) * 100)}%) · ${m[3]} fps · faltam ~${Math.max(1, Math.round(+m[4] / 60))} min`);
  });
  if (v.code !== 0 || !fs.existsSync(path.join(dir, "out/video.mp4"))) throw new Error("render falhou: " + v.out.slice(-600));
  ctx.log("juntando vídeo e áudio…");
  const m = await engine(dir, ["engine/render.js", "mux"], 5 * 60_000);
  const muxed = path.join(dir, "out", `${path.basename(dir)}.mp4`);
  if (m.code !== 0 || !fs.existsSync(muxed)) throw new Error("mux falhou: " + m.out.slice(-600));
  return muxed;
}

// ---------- burned-in captions: 1–3 words at a time, the spoken word in gold ----------
function assTime(t: number) {
  const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), s = t % 60;
  return `${h}:${String(m).padStart(2, "0")}:${s.toFixed(2).padStart(5, "0")}`;
}
export async function burnCaptions(video: string, words: Word[], out: string) {
  const chunks: Word[][] = [];
  let cur: Word[] = [];
  for (const w of words) {
    const len = cur.map((x) => x.w).join(" ").length + w.w.length;
    if (cur.length && (cur.length >= 3 || len > 18 || w.scene !== cur[0].scene || w.t0 - cur[cur.length - 1].t1 > 0.35)) { chunks.push(cur); cur = []; }
    cur.push(w);
    if (/[.!?]$/.test(w.w)) { chunks.push(cur); cur = []; }
  }
  if (cur.length) chunks.push(cur);
  const esc = (s: string) => s.replace(/[{}\\]/g, "");
  // one event per spoken word; each ends exactly when the next begins (never two lines on screen)
  const items: { t0: number; t1: number; text: string }[] = [];
  for (const c of chunks) {
    c.forEach((w, i) => {
      const line = c.map((x, j) => (j === i ? `{\\c&H66C7F2&}${esc(x.w)}{\\c&HFFFFFF&}` : esc(x.w))).join(" ");
      items.push({ t0: w.t0, t1: i < c.length - 1 ? c[i + 1].t0 : w.t1 + 0.25, text: (i === 0 ? "{\\fscx92\\fscy92\\t(0,90,\\fscx100\\fscy100)}" : "") + line });
    });
  }
  const ev = items.map((it, k) => {
    const end = k < items.length - 1 ? Math.min(it.t1, items[k + 1].t0) : it.t1;
    return `Dialogue: 0,${assTime(it.t0)},${assTime(Math.max(it.t0 + 0.05, end))},Cap,,0,0,0,,${it.text}`;
  });
  const ass = `[Script Info]
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
WrapStyle: 2

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Cap,Poppins,78,&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,-1,0,0,0,100,100,0,0,1,7,2,2,60,200,520,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
${ev.join("\n")}
`;
  const file = out.replace(/\.mp4$/, ".ass");
  fs.writeFileSync(file, ass);
  await ffmpeg(["-i", video, "-vf", `subtitles='${filterPath(file)}':fontsdir='${filterPath(config.fontsDir)}'`, "-c:v", "libx264", "-crf", "19", "-preset", "medium", "-c:a", "copy", "-movflags", "+faststart", out]);
  return out;
}
