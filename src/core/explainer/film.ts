const ROOT = process.cwd();
const VENDOR = path.join(ROOT, "vendor/animation-studio");
const ASSETS = path.join(ROOT, "assets/explainer");
const brandColors = () => loadSettings().brandColors;
const objectColors = () => Object.fromEntries(loadSettings().objects.map((o) => [o.name, o.color]));

export type Narr = { words: Word[]; scenes: { t0: number; t1: number }[]; duration: number };

// ---------- project scaffold (engine is MIT, vendored from the animation-studio plugin) ----------
export function scaffold(dir: string, plan: TExplainerPlan, narr: Narr, voiceWav: string) {
  fs.mkdirSync(path.join(dir, "assets"), { recursive: true });
  if (!fs.existsSync(path.join(dir, "engine"))) fs.cpSync(path.join(VENDOR, "engine"), path.join(dir, "engine"), { recursive: true });
  fs.copyFileSync(path.join(VENDOR, "template/index.html"), path.join(dir, "index.html"));
  fs.copyFileSync(path.join(ASSETS, "song.js"), path.join(dir, "song.js"));
  for (const f of ["Poppins-Bold.ttf", "Poppins-Medium.ttf"]) fs.copyFileSync(path.join(config.fontsDir, f), path.join(dir, "assets", f));
  fs.copyFileSync(voiceWav, path.join(dir, "voice.wav"));
  fs.writeFileSync(path.join(dir, "score.js"), scoreJs(plan, narr));
  fs.writeFileSync(path.join(dir, "package.json"), JSON.stringify({ name: path.basename(dir), private: true }));
  installCaptions(dir);
  installMotion(dir);
}

export function removeCaptions(dir: string) {
  const idx = path.join(dir, "index.html");
  fs.writeFileSync(idx, fs.readFileSync(idx, "utf8").replace(/<script src="captions\.js"><\/script>\n?/, ""));
}

/** Motion library (H.M): copied into every film and loaded before film.js. */
export function installMotion(dir: string) {
  fs.copyFileSync(path.join(ASSETS, "motion.js"), path.join(dir, "motion.js"));
  const idx = path.join(dir, "index.html");
  const html = fs.readFileSync(idx, "utf8");
  if (!html.includes("motion.js")) fs.writeFileSync(idx, html.replace('<script src="film.js"></script>', '<script src="motion.js"></script>\n<script src="film.js"></script>'));
}

/** score.js: the timeline the film reads (scenes timed to the narration, word cues, layout zones, brand). */
function scoreJs(plan: TExplainerPlan, narr: Narr) {
  const scenes = plan.scenes.map((s, i) => ({ i, t0: +narr.scenes[i].t0.toFixed(3), t1: +narr.scenes[i].t1.toFixed(3), onScreen: s.onScreen, visual: s.visual, narration: s.narration }));
  const words = narr.words.map((w) => ({ w: w.w, t0: +w.t0.toFixed(3), t1: +w.t1.toFixed(3), scene: w.scene }));
  return `// GENERATED by Vitrine — do not edit by hand (re-run the pipeline instead).
(function () {
  const node = typeof require !== 'undefined';
  const U = node ? require('./engine/util') : globalThis.U;
  const MU = node ? require('./engine/music') : globalThis.MUSIC;
  const FPS = 30, FORMAT = '9:16', STYLE = 'flat';
  const [W, H] = U.formatSize(FORMAT);
  const SAFE = U.safeArea(W, H);
  const DURATION = ${narr.duration.toFixed(3)};
  const clock = MU.makeClock({ bpm: 88, offset: 0 });
  const { T, BEAT } = clock;
  const prog = ['Fmaj7', 'Em7', 'Dm7', 'Cmaj7'];
  const { chords, chordAt } = MU.makeChords(clock, {
    Fmaj7: { notes: ['A3', 'C4', 'E4', 'F4'], bass: 'F2' }, Em7: { notes: ['G3', 'B3', 'D4', 'E4'], bass: 'E2' },
    Dm7: { notes: ['A3', 'C4', 'D4', 'F4'], bass: 'D2' }, Cmaj7: { notes: ['G3', 'B3', 'C4', 'E4'], bass: 'C2' },
  }, Array.from({ length: Math.ceil(DURATION / clock.BAR) + 1 }, (_, b) => [b, 0, 4, prog[b % 4]]));
  const SCENES = ${JSON.stringify(scenes)};
  const WORDS = ${JSON.stringify(words)};
  const norm = (s) => String(s).toLowerCase().normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').replace(/[^a-z0-9%]/g, '');
  // time the narrator says \`word\` in scene i (first match by prefix); fallback = a fraction of the scene
  function cue(i, word, frac = 0.3) {
    const s = SCENES[i]; if (!s) return 0;
    const k = norm(word), w = WORDS.find((x) => x.scene === i && norm(x.w).startsWith(k));
    return w ? w.t0 : s.t0 + (s.t1 - s.t0) * frac;
  }
  const cx = SAFE.x + SAFE.w / 2;
  const ZONES = {
    cx,
    top: { x: SAFE.x + 10, y: SAFE.y, w: SAFE.w - 20, h: 330 },        // titles / numbers
    mid: { x: SAFE.x, y: SAFE.y + 340, w: SAFE.w, h: 1320 - (SAFE.y + 340) }, // the illustration (bigger: fills the screen)
    caption: { y: 1330, h: SAFE.y + SAFE.h - 1330 },                     // RESERVED for the captions
  };
  const BRAND = ${JSON.stringify(brandColors())};
  const OBJECTS = ${JSON.stringify(objectColors())};
  const PALETTE = ${JSON.stringify(plan.palette)};
  const series = ${JSON.stringify(plan.series || "")};
  const HANDLE = ${JSON.stringify(config.brandHandle || "")};
  const markers = Object.fromEntries(SCENES.map((s) => ['scene' + s.i, s.t0]));
  const S = SCENES.reduce((o, s) => (o['scene' + s.i] = [s.t0, s.t1], o), {});
  const SCORE = { FPS, FORMAT, STYLE, W, H, SAFE, DURATION, clock, T, BEAT, chords, chordAt, SCENES, WORDS, cue, ZONES, BRAND, PALETTE, series, HANDLE, OBJECTS, markers, S };
  if (node) module.exports = SCORE; else globalThis.SCORE = SCORE;
})();
`;
}

/** New narration, same animation: rewrite the timeline + voice; the film code reads times from score.js. */
export function retime(dir: string, plan: TExplainerPlan, narr: Narr, voiceWav: string) {
  fs.writeFileSync(path.join(dir, "score.js"), scoreJs(plan, narr));
  fs.copyFileSync(voiceWav, path.join(dir, "voice.wav"));
}

